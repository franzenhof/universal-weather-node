"""Web interface translations: i18n/<lang>.json -> include/i18n_keys.h + include/i18n_table.h.

Single source of truth for every user-visible string of the node's own web
pages (settings, status, log, firmware update) and the setup portal labels.
i18n/en.json is the master (key -> English text); de/fr/es/pt.json carry the
same keys. Placeholders {0} .. {9} are filled by TF() in src/i18n.cpp.

Run by tools/version.py on every build and by the host tests
(test/i18n.test.js checks completeness and placeholders); standalone:
    python3 tools/i18n_gen.py [project_dir]
"""
import json
import re
import sys
from pathlib import Path

LANGS = ["en", "de", "fr", "es", "pt"]   # order = Lang enum in src/i18n.h
KEY_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def load(project_dir):
    base = Path(project_dir) / "i18n"
    tables = {}
    for lang in LANGS:
        p = base / f"{lang}.json"
        tables[lang] = json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}
    return tables


def placeholders(s):
    return sorted(set(re.findall(r"\{(\d)\}", s)))


def problems(tables):
    """List of human-readable problems (empty = consistent)."""
    out = []
    en = tables["en"]
    for k in en:
        if not KEY_RE.match(k):
            out.append(f"en: bad key name {k!r}")
    for lang in LANGS[1:]:
        t = tables[lang]
        for k in en:
            if k not in t or not isinstance(t[k], str) or not t[k].strip():
                out.append(f"{lang}: missing {k}")
            elif placeholders(t[k]) != placeholders(en[k]):
                out.append(f"{lang}: {k}: placeholders {placeholders(t[k])} != en {placeholders(en[k])}")
        for k in t:
            if k not in en:
                out.append(f"{lang}: extra key {k} (not in en.json)")
    return out


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def write_if_changed(path, text):
    path = Path(path)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")


def generate(project_dir):
    tables = load(project_dir)
    en = tables["en"]
    keys = list(en.keys())
    probs = problems(tables)
    if probs:   # summary only (test/i18n.test.js lists them all)
        print(f"i18n: {len(probs)} problems, English used there - first: {probs[0]}")
    inc = Path(project_dir) / "include"
    keys_h = ["#pragma once", "// generated by tools/i18n_gen.py from i18n/*.json - do not edit", "#include <stdint.h>",
              "enum TextId : uint16_t {"]
    keys_h += [f"    T_{k}," for k in keys]
    keys_h += ["    T_COUNT_", "};", ""]
    write_if_changed(inc / "i18n_keys.h", "\n".join(keys_h))
    table = ["#pragma once", "// generated by tools/i18n_gen.py from i18n/*.json - do not edit",
             '#include "i18n_keys.h"', f"static const char* const I18N_TEXT[{len(LANGS)}][T_COUNT_] = {{"]
    for lang in LANGS:
        t = tables[lang]
        table.append("    {")
        for k in keys:
            v = t.get(k)
            if not isinstance(v, str) or not v.strip() or placeholders(v) != placeholders(en[k]):
                v = en[k]
            table.append(f"        {c_str(v)},")
        table.append("    },")
    table += ["};", ""]
    write_if_changed(inc / "i18n_table.h", "\n".join(table))
    return tables


if __name__ == "__main__":
    d = sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).resolve().parent.parent)
    generate(d)
