"""Gzip-compressed embedded web assets (help Markdown, dashboard page).

The firmware stores them as gzip byte arrays and sends them with
`Content-Encoding: gzip` (the browser decompresses); see src/gz_send.h.
Deterministic output: compression level 9, mtime 0, no file name, so the
same source always gives the same bytes (reproducible builds, no needless
recompiles). Used by tools/version.py; checked by test/gz_embed.test.js.
"""
import gzip
import re
import sys
from pathlib import Path


def gzip_bytes(data: bytes) -> bytes:
    # gzip.compress(mtime=0) writes no file name and OS byte 255 (unknown)
    return gzip.compress(data, compresslevel=9, mtime=0)


def c_header(name: str, raw: bytes, guard_define: str) -> str:
    """Header with `extern` declarations, the definition only where guard_define is set."""
    gz = gzip_bytes(raw)
    lines = []
    for i in range(0, len(gz), 24):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in gz[i:i + 24]) + ",")
    return (
        "#pragma once\n"
        "// Generated by tools/gz_embed.py (gzip -9, mtime 0) - do not edit.\n"
        "#include <stddef.h>\n#include <stdint.h>\n#include <pgmspace.h>\n"
        f"extern const uint8_t {name}_GZ[];\n"
        f"extern const size_t {name}_GZ_LEN;   // compressed bytes\n"
        f"extern const size_t {name}_LEN;      // uncompressed bytes\n"
        f"#ifdef {guard_define}\n"
        f"const uint8_t {name}_GZ[] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"
        f"const size_t {name}_GZ_LEN = {len(gz)};\n"
        f"const size_t {name}_LEN = {len(raw)};\n"
        "#endif\n"
    )


def raw_string_body(header_text: str, delim: str) -> str:
    """The content of the C++ raw string R"delim( ... )delim" in a header."""
    m = re.search(r'R"' + re.escape(delim) + r'\((.*?)\)' + re.escape(delim) + '"', header_text, re.S)
    if not m:
        raise RuntimeError(f"raw string R\"{delim}(...)\" not found")
    return m.group(1)


def parse_header_bytes(text: str, name: str) -> bytes:
    """The byte array of a header written by c_header() (for the tests)."""
    m = re.search(name + r"_GZ\[\] PROGMEM = \{(.*?)\};", text, re.S)
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", m.group(1)))


if __name__ == "__main__":
    # gz_embed.py <source> <NAME> <define> [raw-string delimiter] -> header on stdout
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    if len(sys.argv) > 4:
        src = raw_string_body(src, sys.argv[4])
    sys.stdout.write(c_header(sys.argv[2], src.encode("utf-8"), sys.argv[3]))


def bin_header(entries, guard_define: str) -> str:
    """Plain byte arrays (no compression): [(C name, bytes), ...]."""
    out = ["#pragma once", "// Generated by tools/gz_embed.py - do not edit.",
           "#include <stddef.h>", "#include <stdint.h>", "#include <pgmspace.h>"]
    for name, data in entries:
        out.append(f"extern const uint8_t {name}[];\nextern const size_t {name}_LEN;")
    out.append(f"#ifdef {guard_define}")
    for name, data in entries:
        lines = ["    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
        out.append(f"const uint8_t {name}[] PROGMEM = {{\n" + "\n".join(lines) + "\n};")
        out.append(f"const size_t {name}_LEN = {len(data)};")
    out.append("#endif")
    return "\n".join(out) + "\n"
